const mongoose=require('mongoose');
const orderSchema=new mongoose.Schema({
    user:{
        type:mongoose.Schema.Types.ObjectId,
        ref:'User',
        required:true
    },
    orderItems:[
        {
            name:{type:String,required:true},
            qty:{type:Number,required:true,min:1},
            price:{type:Number,required:true},
            product:{type:mongoose.Schema.Types.ObjectId,ref:'Product',required:true}
        }
    ],
    shippingAddress:{
        fullName:{type:String,required:true},
        phone:{type:String,required:true},
        altPhone:{type:String},
        address:{type:String,required:true},
        city:{type:String,required:true},
        district:{type:String,required:true},
        state:{type:String,required:true},
        postalCode:{type:String,required:true},
        country:{type:String,required:true}
    },
    paymentMethod:{type:String,required:true},
    paymentConfirmation:{
        type:String,
        enum:['razorpay','admin'],
        default:undefined
    },
    manualPaymentReference:{type:String},
    paymentConfirmedBy:{
        type:mongoose.Schema.Types.ObjectId,
        ref:'User'
    },
    razorpayOrderId:{type:String},
    paymentResult:{
        razorpayPaymentId:{type:String},
        razorpaySignature:{type:String}
    },
    processingAt:{type:Date},
    shippedAt:{type:Date},
    status:{type:String,enum:['pending','processing','shipped','delivered'],required:true,default:'pending'},
    itemsPrice:{type:Number,required:true,default:0.0},
    taxPrice:{type:Number,required:true,default:0.0},
    promiseFee:{type:Number,required:true,default:0.0},
    shippingPrice:{type:Number,required:true,default:0.0},
    totalPrice:{type:Number,required:true,default:0.0},
    isPaid:{type:Boolean,required:true,default:false},
    paidAt:{type:Date},
    isDelivered:{type:Boolean,required:true,default:false},
    deliveredAt:{type:Date},
    exchangeRequest:{
        status:{type:String,enum:['requested','approved','rejected']},
        reason:{type:String,maxlength:500},
        requestedAt:{type:Date},
        reviewedAt:{type:Date}
    }
},{timestamps:true});

module.exports=mongoose.model('Order',orderSchema);